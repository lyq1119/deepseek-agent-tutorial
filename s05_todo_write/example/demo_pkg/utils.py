"""Utility functions for demo_pkg."""


def add(a: int, b: int) -> int:
    """Return the sum of two integers.

    Args:
        a: The first addend.
        b: The second addend.

    Returns:
        The sum of ``a`` and ``b``.
    """
    return a + b


def multiply(a: int, b: int) -> int:
    """Return the product of two integers.

    Args:
        a: The first factor.
        b: The second factor.

    Returns:
        The product of ``a`` and ``b``.
    """
    return a * b
